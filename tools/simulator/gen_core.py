#!/usr/bin/env python3
"""Generate host-build crates for the fork firmware's core standby UI.

The app simulator (gen_wrappers.py) runs overlay apps; this is its
core-UI sibling. It compiles the fork's actual standby renderer —
`src/ui/standby.rs` + `src/ui/theme.rs` + `src/ui/icons.rs`, copied
verbatim from the fork tree — for the host, once per theme variant,
against a mock `crate::app` (coreui/mock_app.rs) fed by Preston's
real channels/settings and the harness RF model. Each variant is
its own crate because cargo features are per-crate and the theme
is a compile-time feature of the fork, exactly as in the firmware.

Layout emitted (gitignored):

  coresrcs/                verbatim fork UI sources + provenance
  gencore/coreui-<theme>/  one crate per theme: lib (renderer +
                           mock) + bin `sim-standby-<theme>`

The fork tree is copied, never modified. Set BF5RH_FORK to the
bf5rh-fork checkout (default ~/ar5rm-firmware/bf5rh-fork).

Usage: python3 gen_core.py
"""

import os
import shutil
import subprocess
import sys
from pathlib import Path

SIM_DIR = Path(__file__).resolve().parent
COREUI = SIM_DIR / "coreui"
GENCORE = SIM_DIR / "gencore"
FORK = Path(
    os.environ.get("BF5RH_FORK", Path.home() / "ar5rm-firmware" / "bf5rh-fork")
)

# theme id -> display name (fork's ACTIVE_THEME_NAME values)
THEMES = {
    "apx": "APX Pro",
    "clean": "Clean Modern",
    "dense": "Data Dense",
    "minimal": "Minimal Dark",
}

FORK_UI_FILES = ["standby.rs", "theme.rs", "icons.rs"]


def fork_head() -> str:
    try:
        return subprocess.run(
            ["git", "-C", str(FORK), "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except Exception:
        return "unknown"


def main() -> int:
    if not FORK.is_dir():
        print(f"fork tree not found: {FORK} (set BF5RH_FORK)", file=sys.stderr)
        return 1
    for f in FORK_UI_FILES:
        if not (FORK / "src" / "ui" / f).is_file():
            print(f"missing fork source: src/ui/{f}", file=sys.stderr)
            return 1

    srcs = SIM_DIR / "coresrcs"
    if srcs.exists():
        shutil.rmtree(srcs)
    srcs.mkdir(parents=True)
    for f in FORK_UI_FILES:
        shutil.copy2(FORK / "src" / "ui" / f, srcs / f)
    (srcs / "PROVENANCE.txt").write_text(
        f"Fork UI sources copied verbatim from {FORK} @ {fork_head()}\n"
        "Files: src/ui/standby.rs, src/ui/theme.rs, src/ui/icons.rs\n"
        "The fork tree is never modified by the simulator.\n"
    )

    runner_template = (COREUI / "runner_main.rs").read_text()

    for theme_id, theme_name in THEMES.items():
        crate = GENCORE / f"coreui-{theme_id}"
        if crate.exists():
            shutil.rmtree(crate)
        (crate / "src" / "ui").mkdir(parents=True)
        (crate / "src" / "device").mkdir(parents=True)

        lib_ident = f"bf5rh_coreui_{theme_id}"
        (crate / "Cargo.toml").write_text(
            f'[package]\nname = "bf5rh-coreui-{theme_id}"\n'
            'version = "0.0.0"\nedition = "2021"\n\n'
            f'[lib]\nname = "{lib_ident}"\npath = "src/lib.rs"\n\n'
            f'[[bin]]\nname = "sim-standby-{theme_id}"\npath = "src/main.rs"\n\n'
            "[dependencies]\n"
            'embedded-graphics = "0.8"\n'
            'bf5rh-abi = { path = "../../abi" }\n'
            'bf5rh-sim = { path = "../../harness" }\n\n'
            "[features]\n"
            f'default = ["theme-{theme_id}"]\n'
            "theme-apx = []\ntheme-clean = []\ntheme-dense = []\n"
            "theme-minimal = []\n"
        )
        (crate / "src" / "lib.rs").write_text(
            f"//! Core-UI simulator crate for the {theme_name} standby\n"
            "//! variant: the fork's verbatim renderer sources (src/ui/)\n"
            "//! over the mock app/device modules. Generated by\n"
            "//! gen_core.py — do not edit here.\n\n"
            "pub mod app;\npub mod device;\npub mod ui;\n"
        )
        shutil.copy2(COREUI / "mock_app.rs", crate / "src" / "app.rs")
        shutil.copy2(COREUI / "device.rs", crate / "src" / "device.rs")
        shutil.copy2(COREUI / "radio_types.rs", crate / "src" / "device" / "radio.rs")
        shutil.copy2(COREUI / "ui_shim.rs", crate / "src" / "ui.rs")
        for f in FORK_UI_FILES:
            shutil.copy2(srcs / f, crate / "src" / "ui" / f)
        main_rs = (
            runner_template.replace("%%LIB%%", lib_ident)
            .replace("%%THEME_ID%%", theme_id)
            .replace("%%THEME_NAME%%", theme_name)
        )
        (crate / "src" / "main.rs").write_text(main_rs)
        print(f"generated gencore/coreui-{theme_id} (bin sim-standby-{theme_id})")

    print(f"fork sources: {FORK} @ {fork_head()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
