#!/usr/bin/env python3
"""Fetch fresh CelesTrak TLEs and emit the curated .sat list for mkrecord.

Curated set: the amateur satellites Preston is most likely to work from
North Carolina, plus the NOAA weather satellites (RX-only). Frequencies
are the standard published AMSAT band-plan centers; tones use the
firmware subaudio encoding (CTCSS in tenths of a Hz, 0 = none).

Usage:
    python3 make_sat_table.py <out.sat> <out-sidecar.json>

Then build the table with upstream's tooling (mkrecord must exist at
<firmware-tree>/tools/mkrecord/; the port positional is required by
push_sat.py's argparse even in build-only mode, pass a dummy):
    python3 <firmware-tree>/tools/push_sat.py <out.sat> dummy --build-only docs/appdata/satellites.bin
"""
import json
import sys
import urllib.request
from datetime import datetime, timezone

CELESTRAK = [
    "https://celestrak.org/NORAD/elements/gp.php?GROUP=amateur&FORMAT=tle",
    "https://celestrak.org/NORAD/elements/gp.php?GROUP=stations&FORMAT=tle",
    "https://celestrak.org/NORAD/elements/gp.php?GROUP=weather&FORMAT=tle",
]
CELESTRAK_CATNR = "https://celestrak.org/NORAD/elements/gp.php?CATNR={}&FORMAT=tle"

# name (<=10 chars), NORAD id, rx_hz (downlink), tx_hz (uplink, 0 = RX-only),
# rx_tone, tx_tone (firmware subaudio encoding)
SATS = [
    ("ISS",      25544, 437_800_000, 145_990_000, 0,    670),   # ISS voice xband rptr
    ("ISS-APRS", 25544, 145_825_000, 145_825_000, 0,    0),     # ISS packet/APRS
    ("SO-50",    27607, 436_795_000, 145_850_000, 0,    670),
    ("AO-91",    43017, 145_960_000, 435_250_000, 0,    670),
    ("PO-101",   43678, 437_500_000, 145_900_000, 0,    1413),
    ("CAS-3H",   40908, 437_200_000, 144_350_000, 0,    0),
    ("RS-44",    44909, 435_640_000, 145_965_000, 0,    0),     # linear, center freqs
    ("AO-7",     7530,  145_950_000, 432_150_000, 0,    0),     # mode B linear, centers
    ("FO-29",    24278, 435_850_000, 145_950_000, 0,    0),     # linear, center freqs
    ("NOAA-15",  25338, 137_620_000, 0,           0,    0),
    ("NOAA-18",  28654, 137_912_500, 0,           0,    0),
    ("NOAA-19",  33591, 137_100_000, 0,           0,    0),
]


def _absorb(by_id, text):
    lines = [ln.rstrip("\r") for ln in text.splitlines()]
    for i in range(len(lines) - 2):
        if lines[i + 1].startswith("1 ") and lines[i + 2].startswith("2 "):
            try:
                norad = int(lines[i + 1][2:7])
            except ValueError:
                continue
            by_id.setdefault(norad, (lines[i + 1], lines[i + 2]))


def _fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "ar5rm-satpack/1.0"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("ascii", "replace")


def fetch_tles(wanted_ids):
    by_id = {}
    for url in CELESTRAK:
        _absorb(by_id, _fetch(url))
    # Per-catalog-number fallback for anything the groups didn't carry
    # (e.g. the NOAA weather sats are not in the amateur/stations groups).
    for norad in wanted_ids:
        if norad not in by_id:
            _absorb(by_id, _fetch(CELESTRAK_CATNR.format(norad)))
    return by_id


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    out_sat, out_sidecar = sys.argv[1], sys.argv[2]
    tles = fetch_tles([s[1] for s in SATS])
    now = datetime.now(timezone.utc)
    lines = [
        "# AR-5RM satellite table source — generated by make_sat_table.py",
        f"# TLE source: CelesTrak (amateur + stations + weather groups, CATNR fallback), fetched {now.isoformat()}",
        "",
    ]
    sidecar_sats = []
    for name, norad, rx, tx, rx_tone, tx_tone in SATS:
        if norad not in tles:
            print(f"ERROR: NORAD {norad} ({name}) not in fetched TLEs", file=sys.stderr)
            return 1
        l1, l2 = tles[norad]
        lines.append(f"sat {name} {rx} {tx} {rx_tone} {tx_tone}")
        lines.append(f"tle1 {l1}")
        lines.append(f"tle2 {l2}")
        lines.append("")
        sidecar_sats.append({
            "name": name,
            "norad": norad,
            "rx_hz": rx,
            "tx_hz": tx,
            "rx_tone": rx_tone,
            "tx_tone": tx_tone,
            "tle_epoch_raw": l1[18:32].strip(),
        })
    with open(out_sat, "w") as f:
        f.write("\n".join(lines))
    sidecar = {
        "generated_utc": now.isoformat(),
        "tle_source": "CelesTrak GP elements (amateur, stations, weather groups + per-satellite CATNR fallback)",
        "table_bytes": 5120,
        "table_flash_addr": "0x18C000",
        "satellites": sidecar_sats,
    }
    with open(out_sidecar, "w") as f:
        json.dump(sidecar, f, indent=2)
    print(f"wrote {out_sat} ({len(SATS)} sats) and {out_sidecar}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
