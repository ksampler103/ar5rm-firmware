#!/usr/bin/env python3
"""Generate src/baked.rs for the rptbook app from a stock CPS memory image.

Parses the channel area (logical 0x0000..0x8000, 32-byte records in the
bf-5rh `flash_map::Channel` layout) of a decrypted factory/CPS image —
by default Preston's pre-flash backup of the NRF dev unit — and emits a
Rust source file with one `BakedRec` per programmed channel.

The app never writes channel data; this is a read-only snapshot baked in
at build time. The live directory can be superseded at install time by
an injected "RPBK" data block (see src/main.rs header).

Usage: python3 gen_baked.py [image] [out.rs]
Defaults: ~/workspace/ar5rm-backups/2026-11-24-nrf-dev-unit/factory_memory.img
          src/baked.rs (next to this script)
"""

import struct
import sys
from pathlib import Path

DEF_IMG = Path.home() / "workspace/ar5rm-backups/2026-11-24-nrf-dev-unit/factory_memory.img"
DEF_OUT = Path(__file__).resolve().parent / "src" / "baked.rs"

FLAG_DUPLEX = 0x01
FLAG_TX_TONE = 0x02
FLAG_RX_TONE = 0x04


def bcd4(b: bytes) -> int:
    """4 BCD bytes -> deci-Hz integer (bf-5rh bcd4_to_deci_hz)."""
    dec = lambda x: (x >> 4) * 10 + (x & 0x0F)
    return dec(b[3]) * 1_000_000 + dec(b[2]) * 10_000 + dec(b[1]) * 100 + dec(b[0])


def clean_name(raw: bytes, chan_no: int) -> str:
    out = []
    for c in raw:
        if c in (0x00, 0xFF):
            break
        out.append(chr(c) if 32 <= c <= 126 else " ")
    name = "".join(out).rstrip()
    return name if name else f"CH {chan_no}"


def main() -> int:
    img = Path(sys.argv[1]) if len(sys.argv) > 1 else DEF_IMG
    out_path = Path(sys.argv[2]) if len(sys.argv) > 2 else DEF_OUT
    d = img.read_bytes()
    recs = []
    for i in range(0x8000 // 32):
        rec = d[i * 32:(i + 1) * 32]
        if all(x == 0xFF for x in rec):
            continue
        rx_deci = bcd4(rec[0:4])
        if rx_deci == 0:
            continue
        tx_deci = bcd4(rec[4:8])
        rx_hz = rx_deci * 10
        tx_hz = tx_deci * 10
        rx_tone, tx_tone = struct.unpack_from("<HH", rec, 8)
        flags = 0
        if tx_hz != rx_hz:
            flags |= FLAG_DUPLEX
        if tx_tone:
            flags |= FLAG_TX_TONE
        if rx_tone:
            flags |= FLAG_RX_TONE
        recs.append((clean_name(rec[20:32], i + 1), rx_hz, tx_hz, tx_tone, rx_tone, flags))

    lines = [
        "// @generated by gen_baked.py — do not edit by hand.",
        f"// Source: {img.name} ({len(recs)} programmed channels).",
        "// Record layout mirrors the injected RPBK block records in main.rs,",
        "// except names are 12 bytes here (stock NAME_SIZE) vs 16 injected.",
        "",
        "pub struct BakedRec {",
        "    pub name: [u8; 12],",
        "    pub rx_hz: u32,",
        "    pub tx_hz: u32,",
        "    pub tx_tone: u16,",
        "    pub rx_tone: u16,",
        "    pub flags: u8,",
        "}",
        "",
        f"pub static BAKED: &[BakedRec] = &[",
    ]
    for name, rx, tx, tt, rt, fl in recs:
        nb = name.encode("ascii", "replace")[:12].ljust(12, b" ")
        arr = ", ".join(str(b) for b in nb)
        lines.append(
            f"    BakedRec {{ name: [{arr}], rx_hz: {rx}, tx_hz: {tx}, "
            f"tx_tone: {tt}, rx_tone: {rt}, flags: 0x{fl:02X} }}, // {name}"
        )
    lines.append("];")
    lines.append("")
    out_path.write_text("\n".join(lines))
    print(f"wrote {out_path}: {len(recs)} records")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
